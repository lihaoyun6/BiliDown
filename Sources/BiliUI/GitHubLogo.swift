import SwiftUI

/// GitHub 那个 mark（猫的剪影）。设置页「源代码」那行右边摆的就是它。
///
/// 用矢量画的，不是位图：跟着行里的字缩放不会糊，深色浅色底下也不用备两套图。
/// 路径只此一份（下面 `GitHubMark`），iOS 和 mac 两页设置读的是同一个。
public struct GitHubLogo: View {

    /// 边长。默认 18：这个位置原来摆的是一段 `body` 大小的地址文字（17pt），
    /// 换成图标之后重量得跟它相当，不该比那行字更扎眼。
    private let size: CGFloat

    public init(size: CGFloat = 18) {
        self.size = size
    }

    public var body: some View {
        GitHubMark()
            // 普通颜色（次要色），**不是**强调色：这一行的行尾跟旁边那几行
            // （版本信息的值、快捷指令那颗外链图标）是同一种东西，一排扫下来
            // 得是一套。原来那串地址文字是蓝的，是因为它自己就是那一行的值、
            // 又长，得靠颜色把它从标题里分出来；换成一颗图标之后没有这个问题，
            // 而且整行本来就是按钮，不用再靠颜色喊「这儿能点」。
            .fill(.secondary)
            .frame(width: size, height: size)
            // 图标替掉的是一段会念出来的地址文字，所以得给它一个能念的名字：
            // 光一块没有标签的图形，旁白读到这一行就只剩「源代码」了。
            .accessibilityLabel("GitHub")
    }
}

/// 那块剪影本身。
///
/// 路径不是手画的，是从 Simple Icons 的 `github.svg`（24×24 画布，CC0）
/// 离线展开成数字的：App 里不带 SVG 解析器，也不为这张图发请求，
/// 那一串路径展开一次钉在代码里最省事。
private struct GitHubMark: Shape {

    func path(in rect: CGRect) -> Path {
        var path = Path()
        let numbers = Self.outline
        path.move(to: CGPoint(x: numbers[0], y: numbers[1]))
        for i in stride(from: 2, to: numbers.count, by: 6) {
            path.addCurve(
                to: CGPoint(x: numbers[i + 4], y: numbers[i + 5]),
                control1: CGPoint(x: numbers[i], y: numbers[i + 1]),
                control2: CGPoint(x: numbers[i + 2], y: numbers[i + 3])
            )
        }
        // 24×24 是原图的画布，缩到给的那块地方。横竖各缩各的（`Shape` 的惯例），
        // 调用点给的都是正方形，不会走样。
        return path
            .applying(CGAffineTransform(scaleX: rect.width / 24, y: rect.height / 24))
            .offsetBy(dx: rect.minX, dy: rect.minY)
    }

    /// 展开后的那一串数，全在 24×24 那个坐标系里：开头两个是起点，
